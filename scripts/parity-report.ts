import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { UPSTREAM_PARSERS } from "../packages/core/src/generated/upstream-services.ts";

const detection = JSON.parse(
  readFileSync("packages/mime/test/detection-goldens.json", "utf8"),
) as { tikaVersion: string; entries: Array<{ id: string; mediaType: string }> };
const ooxml = JSON.parse(
  readFileSync("packages/parser-office/test/ooxml-goldens.json", "utf8"),
) as { tikaVersion: string; entries: Array<{ id: string }> };
const coverage = JSON.parse(
  readFileSync("tasks/parser-coverage.json", "utf8"),
) as { modules: Record<string, { owner: string; status: string }> };

const statusCounts: Record<string, number> = {};
for (const entry of Object.values(coverage.modules)) {
  statusCounts[entry.status] = (statusCounts[entry.status] ?? 0) + 1;
}

const report = {
  generatedBy: "scripts/parity-report.ts",
  oracle: {
    tikaVersion: detection.tikaVersion,
    detectionFixtures: detection.entries.length,
    ooxmlFixtures: ooxml.entries.length,
  },
  detection: {
    fixtures: detection.entries.map((entry) => ({
      id: entry.id,
      expected: entry.mediaType,
      status: "enforced-by-test",
    })),
  },
  ooxml: {
    fixtures: ooxml.entries.map((entry) => ({
      id: entry.id,
      status: "text+metadata-threshold",
    })),
  },
  parserCoverage: {
    modules: Object.keys(coverage.modules).length,
    upstreamClasses: UPSTREAM_PARSERS.reduce(
      (sum, group) => sum + group.classes.length,
      0,
    ),
    statusCounts,
  },
};

mkdirSync("docs", { recursive: true });
writeFileSync("docs/parity-report.json", `${JSON.stringify(report, null, 2)}\n`);

const lines = [
  "# Parity report",
  "",
  `Oracle: Apache Tika ${detection.tikaVersion}.`,
  "",
  "| Area | Fixtures | Check |",
  "|---|---:|---|",
  `| Detection | ${detection.entries.length} | exact media type |`,
  `| OOXML | ${ooxml.entries.length} | normalized text similarity + metadata |`,
  "",
  `Parser modules mapped: ${report.parserCoverage.modules} (${report.parserCoverage.upstreamClasses} upstream classes).`,
  "",
  "| Coverage status | Modules |",
  "|---|---:|",
  ...Object.entries(statusCounts)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([status, count]) => `| ${status} | ${count} |`),
  "",
  "Generated by `pnpm parity:report`; goldens are checked in and run without Docker.",
  "",
];
writeFileSync("docs/parity-report.md", lines.join("\n"));

const matrix = [
  "# Feature parity matrix",
  "",
  "| Module | Owner | Status |",
  "|---|---|---|",
  ...Object.entries(coverage.modules)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(
      ([module, entry]) =>
        `| \`${module.split("/").at(-1) ?? module}\` | ${entry.owner} | ${entry.status} |`,
    ),
  "",
  "Source: `tasks/parser-coverage.json`. Regenerate with `pnpm parity:report`.",
  "",
];
writeFileSync("docs/feature-parity.md", matrix.join("\n"));
console.log(`wrote docs/parity-report.{json,md}: ${detection.entries.length} detection, ${ooxml.entries.length} OOXML fixtures`);

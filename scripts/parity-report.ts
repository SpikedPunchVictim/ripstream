import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

interface Goldens {
  readonly tikaVersion: string;
  readonly entries?: ReadonlyArray<{ id: string; mediaType?: string }>;
  readonly cases?: ReadonlyArray<{ id: string }>;
}

function goldens(path: string): Goldens {
  return JSON.parse(readFileSync(path, "utf8")) as Goldens;
}

const detection = goldens("packages/mime/test/detection-goldens.json");
const zipContainers = goldens("packages/mime/test/zip-container-goldens.json");
const ooxml = goldens("packages/parser-office/test/ooxml-goldens.json");
const matrix = JSON.parse(readFileSync("docs/parity-matrix.json", "utf8")) as {
  oracle: { tikaVersion: string; parsers: number; typeClaims: number };
  summary: Record<string, number>;
};

const detectionFixtures = detection.entries?.length ?? 0;
const zipFixtures = zipContainers.cases?.length ?? 0;
const ooxmlFixtures = ooxml.entries?.length ?? 0;

const report = {
  generatedBy: "scripts/parity-report.ts",
  oracle: {
    tikaVersion: detection.tikaVersion,
    detectionFixtures,
    zipContainerFixtures: zipFixtures,
    ooxmlFixtures,
  },
  parserMatrix: matrix.summary,
};

mkdirSync("docs", { recursive: true });
writeFileSync("docs/parity-report.json", `${JSON.stringify(report, null, 2)}\n`);

const lines = [
  "# Parity report",
  "",
  `Oracle: Apache Tika ${detection.tikaVersion}.`,
  "",
  "| Area | Fixtures | Check |",
  "|---|---:|---|",
  `| Detection | ${detectionFixtures} | exact media type |`,
  `| ZIP containers | ${zipFixtures} | exact media type, with a typical and a neutral file name |`,
  `| OOXML | ${ooxmlFixtures} | normalized text similarity + metadata |`,
  "",
  `Parser coverage is the generated [parity matrix](parity-matrix.md): ${matrix.oracle.parsers} Tika ${matrix.oracle.tikaVersion} parsers, ${matrix.oracle.typeClaims} media-type claims.`,
  "",
  "| Tier / status | Parsers |",
  "|---|---:|",
  ...Object.entries(matrix.summary)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([key, count]) => `| ${key.replace(".", " / ")} | ${count} |`),
  "",
  "Generated by `pnpm parity:report`; goldens are checked in and run without Docker.",
  "",
];
writeFileSync("docs/parity-report.md", lines.join("\n"));
console.log(
  `wrote docs/parity-report.{json,md}: ${detectionFixtures} detection, ${zipFixtures} zip container, ${ooxmlFixtures} OOXML fixtures`,
);

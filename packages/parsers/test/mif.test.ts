import assert from "node:assert/strict";
import { test } from "node:test";
import { BodyContentHandler, MediaType, Metadata, ParseContext, RipstreamInputStream } from "@spikedpunch/ripstream-core";
import { MifParser, createDefaultParser, createRipstream } from "../src/index.ts";

/*
 * Tika's MIFParser (tika-parser-miscoffice-module) with MIFExtractor and MIFContentHandler: the lines of an Adobe FrameMaker MIF
 * file are read as statements, `<String `...'>` values inside `<Para` are the text, and `<PageType ...>` values are counted into
 * the page counts. MIFParserTest reads testFramemakerMif.mif and expects meta:page-count "1", Content-Type application/x-mif and
 * "Lorem ipsum dolor sit amet, consectetur adipiscing elit" in a <p>. The documents below have the shape of that file.
 * Read from Tika source, not run against a Tika.
 */

const encoder = new TextEncoder();
const ripstream = createRipstream();

const LOREM = "Lorem ipsum dolor sit amet, consectetur adipiscing elit, sed do eiusmod tempor incididunt ut ";

const MIF = [
  "<MIFFile 2019> # Generated by FrameMaker 2019",
  "<Page ",
  " <Unique 94657>",
  " <PageType LeftMasterPage>",
  " <PageTag `Left'>",
  "> # end of Page",
  "<Page ",
  " <PageType RightMasterPage>",
  "> # end of Page",
  "<Page ",
  " <PageType ReferencePage>",
  "> # end of Page",
  "<Page ",
  " <PageType BodyPage>",
  "> # end of Page",
  "<TextFlow ",
  " <TFTag `A'>",
  " <Para ",
  "  <Unique 999328>",
  "  <PgfTag `Body'>",
  "  <ParaLine ",
  "   <TextRectID 19>",
  `   <String \`${LOREM}'>`,
  "  > # end of ParaLine",
  "  <ParaLine ",
  "   <String `labore et dolore magna aliqua.'>",
  "  > # end of ParaLine",
  " > # end of Para",
  "> # end of TextFlow",
  "",
].join("\n");

async function parseDirect(
  text: string | Uint8Array,
  parser: MifParser = new MifParser(),
  context: ParseContext = new ParseContext(),
): Promise<{ text: string; metadata: Metadata }> {
  const stream = await RipstreamInputStream.from(typeof text === "string" ? encoder.encode(text) : text);
  const handler = new BodyContentHandler();
  const metadata = new Metadata();
  try {
    await parser.parse(stream, handler, metadata, context);
  } finally {
    await stream.close();
  }
  return { text: handler.toString(), metadata };
}

/** One Para holding one String statement for each value. */
function paragraph(...values: string[]): string {
  return ["<Para ", ...values.map((value) => `<String \`${value}'>`), "> # end of Para", ""].join("\n");
}

test("the MIF parser claims application/vnd.mif, x-maker and x-mif, and the default registry sends each of them there", async () => {
  const claimed = [...(await new MifParser().getSupportedTypes())].map(String).sort();
  assert.deepEqual(claimed, ["application/vnd.mif", "application/x-maker", "application/x-mif"]);
  const composite = createDefaultParser();
  for (const type of claimed) {
    const [first] = await composite.selectParsers(MediaType.parseOrThrow(type), new ParseContext());
    assert.equal(first?.parser.name, "MIFParser", type);
    assert.equal(first?.kind, "exact", type);
  }
});

test("a MIF file gives the page count, the type application/x-mif and the text, as MIFParserTest expects", async () => {
  const { text, metadata } = await parseDirect(MIF);
  assert.equal(metadata.get("meta:page-count"), "1");
  assert.equal(metadata.get("Content-Type"), "application/x-mif");
  assert.match(text, /Lorem ipsum dolor sit amet, consectetur adipiscing elit/);
});

test("the text is one p for each Para, with the Strings of the paragraph run together", async () => {
  const result = await ripstream.parse(encoder.encode(MIF), { filename: "doc.mif", handlerType: "xml" });
  assert.match(result.text, /<p>Lorem ipsum dolor sit amet, consectetur adipiscing elit, sed do eiusmod tempor incididunt ut labore et dolore magna aliqua\.<\/p>/);
  assert.match(result.text, /<meta name="Content-Type" content="application\/x-mif"><\/meta>/);
});

test("a MIF file through the whole library is detected and written as application/x-mif, with the character set", async () => {
  const result = await ripstream.parse(encoder.encode(MIF), { filename: "doc.mif" });
  assert.equal(result.metadata.get("Content-Type"), "application/x-mif");
  assert.equal(result.metadata.get("Content-Encoding"), "windows-1252");
  assert.equal(result.metadata.get("meta:page-count"), "1");
  assert.match(result.text, /Lorem ipsum/);
});

test("the pages are counted by their PageType: body, the three kinds of master, and reference", async () => {
  const pages = ["BodyPage", "BodyPage", "LeftMasterPage", "RightMasterPage", "OtherMasterPage", "ReferencePage", "ReferencePage", "ReferencePage", "Other"];
  const { metadata } = await parseDirect(pages.map((page) => `<Page \n <PageType ${page}>\n> # end of Page\n`).join(""));
  assert.equal(metadata.get("meta:page-count"), "2");
  assert.equal(metadata.get("mif:master-page-count"), "3");
  assert.equal(metadata.get("mif:reference-page-count"), "3");
  assert.equal(metadata.get("mif:total-page-count"), "8");
});

test("a file with no pages has all four counts at 0", async () => {
  const { metadata } = await parseDirect("<MIFFile 2019>\n");
  assert.equal(metadata.get("meta:page-count"), "0");
  assert.equal(metadata.get("mif:master-page-count"), "0");
  assert.equal(metadata.get("mif:reference-page-count"), "0");
  assert.equal(metadata.get("mif:total-page-count"), "0");
});

test("a String's backtick and closing quote are removed, and the value is XML-escaped before it is written", async () => {
  // MIFExtractor.processTag: removeStart("`"), removeEnd("'"), then StringEscapeUtils.escapeXml. The handler writes the result
  // as text, so a text handler shows the escapes.
  const { text } = await parseDirect(paragraph("fish & chips", "1 < 2 > 0", 'say "hi"', "it&apos;s"));
  assert.match(text, /fish &amp; chips/);
  assert.match(text, /1 &lt; 2 &gt; 0/);
  assert.match(text, /say &quot;hi&quot;/);
  assert.match(text, /it&amp;apos;s/);
});

test("a String value without the backtick and quote is written as it is", async () => {
  const { text } = await parseDirect("<Para \n<String plain>\n> # end of Para\n");
  assert.match(text, /plain/);
});

test("escapeXml drops the control characters XML 1.0 forbids", async () => {
  // From memory of commons-lang3's StringEscapeUtils.ESCAPE_XML10, which is not in the Tika source tree.
  const { text } = await parseDirect(paragraph("a" + String.fromCharCode(1) + "b" + String.fromCharCode(0x0b) + "c"));
  assert.match(text, /abc/);
});

test("escapeXml writes DEL and the C1 range as numeric references, and leaves U+00FF alone", async () => {
  const { text } = await parseDirect(paragraph("d" + String.fromCharCode(0xff) + "e" + String.fromCharCode(0x7f) + "f" + String.fromCharCode(0x9f) + "g"));
  assert.match(text, new RegExp("d" + String.fromCharCode(0xff) + "e&#127;f&#159;g"));
});

test("a String outside any Para is still written", async () => {
  const { text } = await parseDirect("<String `loose'>\n<Para \n> # end of Para\n<Para \n<ParaLine \n<String `inside'>\n> # end of ParaLine\n> # end of Para\n");
  assert.match(text, /loose/);
  assert.match(text, /inside/);
});

test("a close line that names a different element ends the open one without popping it, and a close with none open is ignored", async () => {
  // MIFExtractor pops only when the name after the last space equals the open element's; it writes the end either way.
  // An empty stack throws EmptyStackException, which it swallows.
  const { text, metadata } = await parseDirect("> # end of nothing\n<Para \n<String `one'>\n> # end of Wrong\n<String `two'>\n> # end of Para\n> # end of Para\n");
  assert.match(text, /one/);
  assert.match(text, /two/);
  assert.equal(metadata.get("meta:page-count"), "0");
});

test("CR, LF and CRLF all end a line, and the last line needs no terminator", async () => {
  const { text } = await parseDirect("<Para \r<String `one'>\r\n<String `two'>\n> # end of Para\r\n<Para \n<String `three'>");
  assert.match(text, /one/);
  assert.match(text, /two/);
  assert.match(text, /three/);
});

test("a CRLF split across two reads is one line end", async () => {
  // The stream is read in chunks; a \r at the end of one must not be taken for a line end of its own plus an empty line.
  const parts = ["<Para \r", "\n<String `one'>\r", "\n> # end of Para\r", "\n"];
  const bytes = encoder.encode(parts.join(""));
  const { text } = await parseDirect(bytes);
  assert.match(text, /one/);
});

test("Java's trim() strips every character up to U+0020, and its . does not match U+2028", async () => {
  // java.lang.String.trim() takes control characters off both ends, so a line that starts with one is still a statement.
  const trimmed = await parseDirect(paragraph("x").replace("<String `x'>", "\u0001\u0002 <String `kept'>"));
  assert.match(trimmed.text, /kept/);
  // The regex `(<(\S*))(\s)(.*)(\>).*` is matched in full, and . stops at U+0085, U+2028 and U+2029: such a line is no statement.
  for (const terminator of ["\u0085", "\u2028", "\u2029"]) {
    const { text } = await parseDirect(paragraph(`drop${terminator}me`));
    assert.doesNotMatch(text, /drop/, JSON.stringify(terminator));
  }
});

test("Java's \\S and \\s are ASCII: a no-break space does not end the element name", async () => {
  // `<String\u00a0`x'>` has no \s after the name, so it is no statement; `<String\f`x'>` has one.
  const noBreak = await parseDirect("<Para \n<String\u00a0`nbsp'>\n> # end of Para\n");
  assert.doesNotMatch(noBreak.text, /nbsp/);
  const formFeed = await parseDirect("<Para \n<String\f`ff'>\n> # end of Para\n");
  assert.match(formFeed.text, /ff/);
});

test("an open line takes the name up to the first space", async () => {
  // `<Para x <y` is the open element "Para"; it is closed by the close line that ends in "Para".
  const { text } = await parseDirect("<Para x <y\n<String `inside'>\n> # end of Para\n<String `outside'>\n");
  assert.match(text, /inside/);
  assert.match(text, /outside/);
});

test("the character set is detected: a Latin-1 file is read as Latin-1", async () => {
  const input = new Uint8Array([
    ...encoder.encode("<Para \n<String `caf"),
    0xe9,
    ...encoder.encode(" au lait '>\n> # end of Para\n"),
  ]);
  const { text, metadata } = await parseDirect(input);
  assert.match(metadata.get("Content-Encoding") ?? "", /windows-1252|ISO-8859-1/i);
  assert.match(text, /café au lait/);
});

test("hostile: a line with no end is a LimitExceededError at the line cap, not a buffer of the whole file", async () => {
  await assert.rejects(parseDirect(`<String \`${"x".repeat(11_000_000)}`), (error: Error) => error.name === "LimitExceededError");
  await assert.rejects(
    parseDirect(`<String \`${"x".repeat(5_000)}'>`, new MifParser({ maxLineChars: 1_000 })),
    (error: Error) => error.name === "LimitExceededError",
  );
});

test("hostile: unclosed open lines are a LimitExceededError once their names pass the cap, not a stack without end", async () => {
  // Each open line holds its name and one more character; the default cap is 1,000,000 characters of them.
  const name = "n".repeat(10_000);
  await assert.rejects(parseDirect(`<${name}\n`.repeat(200)), (error: Error) => error.name === "LimitExceededError");
  await assert.rejects(
    parseDirect("<a\n".repeat(20_000), new MifParser({ maxOpenChars: 10_000 })),
    (error: Error) => error.name === "LimitExceededError",
  );
});

test("hostile: names that are closed again do not count against the cap", async () => {
  const { metadata } = await parseDirect("<Page \n> # end of Page\n".repeat(20_000), new MifParser({ maxOpenChars: 100 }));
  assert.equal(metadata.get("meta:page-count"), "0");
});

test("hostile: a hundred thousand Strings are bounded by the output limit", async () => {
  const hostile = paragraph(...Array.from({ length: 100_000 }, () => "x".repeat(50)));
  await assert.rejects(
    ripstream.parse(encoder.encode(hostile), { filename: "big.mif", limits: { maxOutputChars: 10_000 } }),
    (error: Error) => error.name === "LimitExceededError" || error.name === "WriteLimitReachedError",
  );
});

test("hostile: close lines under an open Para are bounded by the output limit", async () => {
  // Each close line whose name differs from the open element's writes another </p> and pops nothing.
  await assert.rejects(
    ripstream.parse(encoder.encode(`<Para \n${">\n".repeat(200_000)}`), { filename: "ends.mif", limits: { maxOutputChars: 10_000 } }),
    (error: Error) => error.name === "LimitExceededError" || error.name === "WriteLimitReachedError",
  );
});

test("hostile: a binary FrameMaker file is read as text without a failure", async () => {
  // testMIF.mif in Tika is the binary form ("<MakerFile 5.5Q>" and bytes); it carries no MIF statements to read.
  const noise = new Uint8Array(200_000);
  for (let index = 0; index < noise.length; index++) noise[index] = (index * 131 + 7) & 0xff;
  const { metadata } = await parseDirect(new Uint8Array([...encoder.encode("<MakerFile 5.5Q>\n"), ...noise]));
  assert.equal(metadata.get("Content-Type"), "application/x-mif");
});

test("the line cap is inclusive: a line of exactly maxLineChars is read, one more character is a limit", async () => {
  const parser = new MifParser({ maxLineChars: 20 });
  // "<String `" and "'>" are 11 characters.
  const exact = await parseDirect(`<String \`${"x".repeat(9)}'>`, parser);
  assert.match(exact.text, /xxxxxxxxx/);
  await assert.rejects(parseDirect(`<String \`${"x".repeat(10)}'>`, parser), (error: Error) => error.name === "LimitExceededError");
});

test("the open-name cap is inclusive: names and one more character each, up to maxOpenChars, are read", async () => {
  const parser = new MifParser({ maxOpenChars: 6 });
  await parseDirect("<abcde\n", parser);
  await assert.rejects(parseDirect("<abcdef\n", parser), (error: Error) => error.name === "LimitExceededError");
});

test("tk:detected-encoding is the charset the MIF text was read with, as AutoDetectReader writes it (tikajs-68os.65)", async () => {
  const { metadata } = await parseDirect(MIF);
  assert.equal(metadata.get("tk:detected-encoding"), "windows-1252");
});

test("a UTF-8 character split across two reads is one character", async () => {
  // The stream hands out 64 KiB at a time: put the two bytes of an é on either side of the first 64 KiB.
  const head = encoder.encode("<Para \n<String `é'>\n<String `");
  const input = Uint8Array.from([
    ...head,
    ...encoder.encode("x".repeat(64 * 1024 - 1 - head.length)),
    ...encoder.encode("é'>\n> # end of Para\n"),
  ]);
  assert.equal(input[64 * 1024 - 1], 0xc3);
  const { text } = await parseDirect(input);
  assert.match(text, /xé/);
});

test("a UTF-8 character cut off at the end of the file is decoded to U+FFFD, and that character is in the last line", async () => {
  // The last line is `<Para` and a lead byte with nothing after it: an open line whose name is five characters with the U+FFFD.
  const input = Uint8Array.from([...encoder.encode("<String `é'>\n<Para"), 0xc3]);
  await assert.rejects(parseDirect(input, new MifParser({ maxOpenChars: 5 })), (error: Error) => error.name === "LimitExceededError");
  const ended = Uint8Array.from([...encoder.encode("<String `é'>\n<Para")]);
  await parseDirect(ended, new MifParser({ maxOpenChars: 5 }));
});

test("the error for a line over the cap says it is a MIF line", async () => {
  await assert.rejects(
    parseDirect(`<String \`${"x".repeat(50)}'>`, new MifParser({ maxLineChars: 10 })),
    (error: Error) => error.name === "LimitExceededError" && error.message.includes("a MIF line"),
  );
});

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

interface UpstreamRow {
  readonly v3: string;
  readonly v4: string;
  readonly egressOnly?: true;
}

const source = readFileSync(new URL("../data/upstream/metadata-migration-3x-4x.json", import.meta.url), "utf8");
const rows = JSON.parse(source) as UpstreamRow[];

for (const [index, row] of rows.entries()) {
  const extra = Object.keys(row).filter((key) => key !== "v3" && key !== "v4" && key !== "egressOnly");
  if (typeof row.v3 !== "string" || row.v3 === "" || typeof row.v4 !== "string" || row.v4 === "" || extra.length > 0) {
    throw new Error(`row ${index} of metadata-migration-3x-4x.json is not {"v3","v4"[,"egressOnly"]}: ${JSON.stringify(row)}`);
  }
  if (row.egressOnly !== undefined && row.egressOnly !== true) {
    throw new Error(`row ${index} of metadata-migration-3x-4x.json has egressOnly other than true: ${JSON.stringify(row)}`);
  }
}

const lines: string[] = [];
lines.push("// Generated by scripts/generate-metadata-migration.ts — do not edit.");
lines.push("// Upstream: apache/tika tika-core metadata-migration-3x-4x.json.");
lines.push(`// metadata-migration-3x-4x sha256: ${createHash("sha256").update(source).digest("hex")}`);
lines.push("");
lines.push("/** The `v4` of a 3.x key that 4.x no longer emits. */");
lines.push('export const METADATA_MIGRATION_DROPPED = "DROPPED";');
lines.push("");
lines.push("/**");
lines.push(" * A key whose spelling changed between Tika 3.x and 4.x. `egressOnly` marks a row applied only when rewriting 4.x keys");
lines.push(" * to 3.x, for a 3.x spelling that several 4.x keys share or that is unsafe to rewrite on the way in.");
lines.push(" */");
lines.push("export interface MetadataMigrationRow {");
lines.push("  readonly v3: string;");
lines.push("  readonly v4: string;");
lines.push("  readonly egressOnly?: true;");
lines.push("}");
lines.push("");
lines.push("export const METADATA_MIGRATION_ROWS: readonly MetadataMigrationRow[] = [");
for (const row of rows) lines.push(`  ${JSON.stringify(row)},`);
lines.push("];");

writeFileSync(new URL("../src/generated/metadata-migration.ts", import.meta.url), `${lines.join("\n")}\n`);

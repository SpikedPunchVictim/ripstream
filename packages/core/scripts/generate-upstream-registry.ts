import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";

const REF = "3.3.3";
const TREE_URL = `https://api.github.com/repos/apache/tika/git/trees/${REF}?recursive=1`;
const RAW = `https://raw.githubusercontent.com/apache/tika/${REF}/`;
const SERVICES = {
  parsers: "org.apache.tika.parser.Parser",
  detectors: "org.apache.tika.detect.Detector",
  encodingDetectors: "org.apache.tika.detect.EncodingDetector",
} as const;

interface TreeEntry {
  readonly path: string;
  readonly type: string;
}

interface ServiceGroup {
  readonly module: string;
  readonly classes: readonly string[];
}

async function main(): Promise<void> {
  const response = await fetch(TREE_URL, {
    headers: { "User-Agent": "ripstream-registry-generator" },
  });
  if (!response.ok) {
    throw new Error(`GitHub tree request failed: ${response.status}`);
  }
  const tree = (await response.json()) as { tree: TreeEntry[]; sha: string };
  const paths = tree.tree
    .filter(
      (entry) =>
        entry.type === "blob" &&
        entry.path.includes("/src/main/resources/META-INF/services/") &&
        !entry.path.includes("/src/test/"),
    )
    .map((entry) => entry.path)
    .sort();

  const groups: Record<keyof typeof SERVICES, ServiceGroup[]> = {
    parsers: [],
    detectors: [],
    encodingDetectors: [],
  };
  const contents: string[] = [];

  for (const path of paths) {
    const service = Object.entries(SERVICES).find(([, name]) =>
      path.endsWith(`/META-INF/services/${name}`),
    );
    if (service === undefined) continue;
    const raw = await fetch(`${RAW}${path}`, {
      headers: { "User-Agent": "ripstream-registry-generator" },
    });
    if (!raw.ok) throw new Error(`Fetch failed for ${path}: ${raw.status}`);
    const text = await raw.text();
    contents.push(`${path}\n${text}`);
    const classes = [
      ...new Set(
        text
          .split(/\r?\n/)
          .map((line) => line.replace(/#.*/, "").trim())
          .filter((line) => line.length > 0),
      ),
    ].sort();
    const module = path.split("/src/main/")[0] ?? path;
    groups[service[0] as keyof typeof SERVICES].push({ module, classes });
  }

  for (const key of Object.keys(groups) as Array<keyof typeof SERVICES>) {
    groups[key].sort((a, b) => a.module.localeCompare(b.module));
  }

  const checksum = createHash("sha256").update(contents.join("\n")).digest("hex");
  const lines: string[] = [
    "// Generated by scripts-generate-upstream-registry.ts — do not edit.",
    `// Upstream: apache/tika ${REF}, tree ${tree.sha}.`,
    `// service files sha256: ${checksum}`,
    "",
    "export interface UpstreamServiceGroup {",
    "  readonly module: string;",
    "  readonly classes: readonly string[];",
    "}",
    "",
  ];
  for (const key of Object.keys(groups) as Array<keyof typeof SERVICES>) {
    const constant = key === "parsers"
      ? "UPSTREAM_PARSERS"
      : key === "detectors"
        ? "UPSTREAM_DETECTORS"
        : "UPSTREAM_ENCODING_DETECTORS";
    lines.push(`export const ${constant}: readonly UpstreamServiceGroup[] = [`);
    for (const group of groups[key]) {
      lines.push(`  ${JSON.stringify(group)},`);
    }
    lines.push("];", "");
  }
  const classCount = (key: keyof typeof SERVICES): number =>
    new Set(groups[key].flatMap((group) => group.classes)).size;
  lines.push("export const UPSTREAM_SERVICE_STATS = Object.freeze({");
  lines.push(`  ref: ${JSON.stringify(REF)},`);
  lines.push(`  parserClasses: ${classCount("parsers")},`);
  lines.push(`  detectorClasses: ${classCount("detectors")},`);
  lines.push(`  encodingDetectorClasses: ${classCount("encodingDetectors")},`);
  lines.push("});");

  writeFileSync(
    new URL("../src/generated/upstream-services.ts", import.meta.url),
    `${lines.join("\n")}\n`,
  );
  console.log(
    `generated upstream services: ${classCount("parsers")} parsers, ${classCount("detectors")} detectors, ${classCount("encodingDetectors")} encodings`,
  );
}

await main();

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

interface UpstreamKey {
  readonly key: string;
  readonly namespace: string;
  readonly valueType: string;
  readonly cardinality: string;
  readonly module: string;
}

interface UpstreamNamespace {
  readonly prefix: string;
  readonly provenance: string;
  readonly description: string;
  readonly module: string;
}

interface UpstreamField {
  readonly class: string;
  readonly field: string;
  readonly key: string;
}

const base = new URL("../data/upstream/", import.meta.url);
const keysSource = readFileSync(new URL("metadata-keys.json", base), "utf8");
const namespacesSource = readFileSync(
  new URL("metadata-open-namespaces.json", base),
  "utf8",
);
const fieldsSource = readFileSync(
  new URL("metadata-key-fields.json", base),
  "utf8",
);
const keys = JSON.parse(keysSource) as UpstreamKey[];
const namespaces = JSON.parse(namespacesSource) as UpstreamNamespace[];
const fields = JSON.parse(fieldsSource) as UpstreamField[];

const checksum = (value: string): string =>
  createHash("sha256").update(value).digest("hex");

const lines: string[] = [];
lines.push("// Generated by scripts/generate-metadata-schema.ts — do not edit.");
lines.push("// Upstream: apache/tika tika-metadata-schema resources.");
lines.push(`// metadata-keys sha256: ${checksum(keysSource)}`);
lines.push(`// metadata-open-namespaces sha256: ${checksum(namespacesSource)}`);
lines.push(`// metadata-key-fields sha256: ${checksum(fieldsSource)}`);
lines.push("");
lines.push("export type MetadataValueType =");
lines.push(
  "  | \"TEXT\"\n  | \"INTEGER\"\n  | \"REAL\"\n  | \"RATIONAL\"\n  | \"BOOLEAN\"\n  | \"DATE\"\n  | \"URI\"\n  | \"JSON\"\n  | \"OPEN_CHOICE\"\n  | \"CLOSED_CHOICE\";",
);
lines.push("");
lines.push("export type MetadataCardinality = \"SIMPLE\" | \"BAG\" | \"SEQ\";");
lines.push("");
lines.push("export interface MetadataKeyDefinition {");
lines.push("  readonly key: string;");
lines.push("  readonly namespace: string;");
lines.push("  readonly valueType: MetadataValueType;");
lines.push("  readonly cardinality: MetadataCardinality;");
lines.push("  readonly module: string;");
lines.push("}");
lines.push("");
lines.push("export interface MetadataNamespaceDefinition {");
lines.push("  readonly prefix: string;");
lines.push("  readonly provenance: string;");
lines.push("  readonly description: string;");
lines.push("  readonly module: string;");
lines.push("}");
lines.push("");
lines.push("export interface MetadataFieldDefinition {");
lines.push("  readonly class: string;");
lines.push("  readonly field: string;");
lines.push("  readonly key: string;");
lines.push("}");
lines.push("");
lines.push(`export const METADATA_KEYS: readonly MetadataKeyDefinition[] = [`);
for (const key of keys) {
  lines.push(
    `  ${JSON.stringify({
      key: key.key,
      namespace: key.namespace,
      valueType: key.valueType,
      cardinality: key.cardinality,
      module: key.module,
    })} ,`.replace("} ,", "},"),
  );
}
lines.push("];");
lines.push("");
lines.push(
  "export const METADATA_NAMESPACES: readonly MetadataNamespaceDefinition[] = [",
);
for (const namespace of namespaces) {
  lines.push(`  ${JSON.stringify(namespace)},`);
}
lines.push("];");
lines.push("");
lines.push(
  "export const METADATA_FIELDS: readonly MetadataFieldDefinition[] = [",
);
for (const field of fields) {
  lines.push(`  ${JSON.stringify(field)},`);
}
lines.push("];");
lines.push("");
lines.push("const byKey = new Map(METADATA_KEYS.map((entry) => [entry.key, entry]));");
lines.push("");
lines.push("/** Exact, case-sensitive lookup matching upstream metadata keys. */");
lines.push(
  "export function metadataKeyDefinition(key: string): MetadataKeyDefinition | undefined {\n  return byKey.get(key);\n}",
);
lines.push("");
lines.push("export function isKnownMetadataKey(key: string): boolean {");
lines.push("  return byKey.has(key);");
lines.push("}");
lines.push("");
lines.push("export function metadataKeyNamespace(key: string): string {");
lines.push("  const colon = key.indexOf(\":\");");
lines.push("  return colon === -1 ? \"\" : key.slice(0, colon);");
lines.push("}");
lines.push("");
lines.push(
  "const openPrefixes = METADATA_NAMESPACES.map((entry) => entry.prefix);",
);
lines.push("");
lines.push("/** Keys in open namespaces are valid even when not enumerated. */");
lines.push("export function isOpenMetadataNamespaceKey(key: string): boolean {");
lines.push(
  "  return openPrefixes.some((prefix) => prefix.length > 0 && key.startsWith(prefix));",
);
lines.push("}");
lines.push("");
lines.push("export const METADATA_SCHEMA_STATS = Object.freeze({");
lines.push(`  keys: ${keys.length},`);
lines.push(`  namespaces: ${namespaces.length},`);
lines.push(`  fields: ${fields.length},`);
lines.push("});");

writeFileSync(
  new URL("../src/generated/metadata-schema.ts", import.meta.url),
  `${lines.join("\n")}\n`,
);
